class Figure(base.Figure):
    def save(self):
        super().save()
        path = OUT / f'figure-{self.number:02}.html'
        html = path.read_text()
        html = html.replace('.frame{width:960px}', '.frame{max-width:1040px;margin:auto}.diagram-container{overflow-x:auto}svg{min-width:960px}')
        html = html.replace('<svg ', '<div class="diagram-container"><svg ', 1).replace('</svg>', '</svg></div>', 1)
        path.write_text(html)


